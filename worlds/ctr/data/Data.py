def get_flaglist_from_adv_file(curr_adv_file_rewards: list[int]) -> dict[str, bool]:
    flaglist = dict()

    for (location_name, (array_index, bitmask)) in checks_table.items():
        flaglist[location_name] = bool(curr_adv_file_rewards[array_index] & bitmask)

    return flaglist
